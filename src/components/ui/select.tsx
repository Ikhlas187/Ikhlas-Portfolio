function SelectTrigger({
  className,
  children,
  ...props
}: SelectPrimitive.Trigger.Props) {
  return (
    <SelectPrimitive.Trigger
      data-slot="select-trigger"
      className={cn(
        "group flex w-fit cursor-pointer items-center justify-between gap-2 rounded-[10px] border border-[color-mix(in_srgb,var(--color-black)_10%,transparent)] bg-white px-3.5 py-2.5 font-sans text-black whitespace-nowrap transition-colors duration-200 outline-none select-none hover:bg-[color-mix(in_srgb,var(--color-black)_4%,var(--color-white))] focus-visible:ring-2 focus-visible:ring-[color-mix(in_srgb,var(--color-black)_30%,transparent)] disabled:cursor-not-allowed disabled:opacity-50 data-popup-open:bg-[color-mix(in_srgb,var(--color-black)_4%,var(--color-white))] *:data-[slot=select-value]:flex *:data-[slot=select-value]:items-center *:data-[slot=select-value]:gap-2 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
        className
      )}
      {...props}
    >
      {children}
      <SelectPrimitive.Icon
        render={
          <ChevronDownIcon className="pointer-events-none size-[18px] text-[color-mix(in_srgb,var(--color-black)_62%,var(--color-white))] transition-transform duration-200 group-data-popup-open:rotate-180" />
        }
      />
    </SelectPrimitive.Trigger>
  )
}

function SelectContent({
  className,
  children,
  side = "bottom",
  sideOffset = 8,
  align = "center",
  alignOffset = 0,
  alignItemWithTrigger = false,
  ...props
}: SelectPrimitive.Popup.Props &
  Pick<
    SelectPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset" | "alignItemWithTrigger"
  >) {
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Positioner
        side={side}
        sideOffset={sideOffset}
        align={align}
        alignOffset={alignOffset}
        alignItemWithTrigger={alignItemWithTrigger}
        className="isolate z-[95]"
      >
        <SelectPrimitive.Popup
          data-slot="select-content"
          data-align-trigger={alignItemWithTrigger}
          className={cn(
            "relative isolate max-h-(--available-height) w-(--anchor-width) origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-[10px] border border-[color-mix(in_srgb,var(--color-black)_6%,transparent)] bg-[color-mix(in_srgb,var(--color-black)_5%,var(--color-white))] p-2 font-sans text-black shadow-[0_4px_20px_color-mix(in_srgb,var(--color-black)_8%,transparent)] duration-150 data-[side=bottom]:slide-in-from-top-1 data-[side=top]:slide-in-from-bottom-1 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95",
            className
          )}
          {...props}
        >
          <SelectScrollUpButton />
          <SelectPrimitive.List>{children}</SelectPrimitive.List>
          <SelectScrollDownButton />
        </SelectPrimitive.Popup>
      </SelectPrimitive.Positioner>
    </SelectPrimitive.Portal>
  )
}

